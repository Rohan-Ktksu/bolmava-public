export type Lang = 'en' | 'te'
const dict = { en, te }
const STORAGE_KEY = 'bolmava.lang' // a display preference, never identity

function stored(): Lang | null {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    return v === 'en' || v === 'te' ? v : null
  } catch {
    return null
  }
}

type Ctx = { lang: Lang; chosen: boolean; setLang: (l: Lang) => void; t: (k: Key, vars?: Record<string, string | number>) => string }
const LanguageContext = createContext<Ctx>(null!)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => stored() ?? 'en')
  const [chosen, setChosen] = useState(() => stored() !== null)
  useEffect(() => void (document.documentElement.lang = lang), [lang])
  const setLang = (l: Lang) => {
    setLangState(l)
    setChosen(true)
    try {
      localStorage.setItem(STORAGE_KEY, l)
    } catch {
      /* private mode: choice lasts for this page only */
    }
  }
  const t = (k: Key, vars?: Record<string, string | number>) =>
    dict[lang][k].replace(/\{(\w+)\}/g, (_, v) => String(vars?.[v] ?? ''))
  return <LanguageContext value={{ lang, chosen, setLang, t }}>{children}</LanguageContext>
}

export const useLang = () => useContext(LanguageContext)

export function useDate() {
  const { lang } = useLang()
  return (iso: string) => formatIst(iso, lang)
}

export const productName = (lang: string, p: { name: string; name_te: string | null }) => (lang === 'te' && p.name_te ? p.name_te : p.name)
